import type { Archive } from '../archive/schema';
import { groundedAnswer, type GroundedOptions } from '../chat/grounded';
import type { SemanticIndex } from '../retrieval/search';
import { IN_SCOPE, OUT_OF_SCOPE } from './questions';

export interface EvalReport {
  inScope: number;
  outOfScope: number;
  /** Fraction of in-scope questions whose answering memory is in the top k retrieved (no threshold). */
  recallAt: Record<number, number>;
  /** Fraction of in-scope questions answered (not abstained) with the right memory cited. */
  groundingRate: number;
  /** Fraction of in-scope questions answered with a wrong memory (the worst failure). */
  wrongAnswerRate: number;
  /** Fraction of in-scope questions the system abstained on (missed answers). */
  falseAbstainRate: number;
  /** Of all abstentions, the fraction that were correct (question was out of scope). */
  abstentionPrecision: number;
  /** Of all out-of-scope questions, the fraction abstained on. */
  abstentionRecall: number;
  /** Misses, for the report: question and what happened. */
  failures: { q: string; expected: string | null; got: string[] }[];
}

export const RECALL_KS = [1, 3, 5];

/** Runs the whole eval set through retrieval and the grounded answerer. Deterministic. */
export async function runEval(
  archive: Archive,
  index: SemanticIndex,
  opts: GroundedOptions = {},
): Promise<EvalReport> {
  const hitsAt = Object.fromEntries(RECALL_KS.map((k) => [k, 0])) as Record<number, number>;
  let grounded = 0;
  let wrong = 0;
  let falseAbstain = 0;
  let abstainedInScope = 0;
  const failures: EvalReport['failures'] = [];

  for (const { q, memoryId } of IN_SCOPE) {
    const hits = await index.search(q, Math.max(...RECALL_KS));
    for (const k of RECALL_KS)
      if (hits.slice(0, k).some((h) => h.memoryId === memoryId)) hitsAt[k]!++;
    const r = await groundedAnswer(archive, index, q, opts);
    if (r.abstained) {
      falseAbstain++;
      abstainedInScope++;
      failures.push({ q, expected: memoryId, got: [] });
    } else if (r.citations.some((c) => c.memoryId === memoryId)) grounded++;
    else {
      wrong++;
      failures.push({ q, expected: memoryId, got: r.citations.map((c) => c.memoryId) });
    }
  }
  let abstainedOut = 0;
  for (const q of OUT_OF_SCOPE) {
    const r = await groundedAnswer(archive, index, q, opts);
    if (r.abstained) abstainedOut++;
    else failures.push({ q, expected: null, got: r.citations.map((c) => c.memoryId) });
  }
  const n = IN_SCOPE.length;
  const abstentions = abstainedOut + abstainedInScope;
  return {
    inScope: n,
    outOfScope: OUT_OF_SCOPE.length,
    recallAt: Object.fromEntries(RECALL_KS.map((k) => [k, hitsAt[k]! / n])) as Record<
      number,
      number
    >,
    groundingRate: grounded / n,
    wrongAnswerRate: wrong / n,
    falseAbstainRate: falseAbstain / n,
    abstentionPrecision: abstentions ? abstainedOut / abstentions : 1,
    abstentionRecall: abstainedOut / OUT_OF_SCOPE.length,
    failures,
  };
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

/** Markdown for docs/EVALS.md. */
export function renderReport(r: EvalReport, embedder: string, threshold: number): string {
  const rows = [
    ...RECALL_KS.map((k) => `| recall@${k} | ${pct(r.recallAt[k]!)} | right memory in top ${k} |`),
    `| grounding rate | ${pct(r.groundingRate)} | answered with the right memory cited |`,
    `| wrong-answer rate | ${pct(r.wrongAnswerRate)} | answered, but cited the wrong memory |`,
    `| false-abstain rate | ${pct(r.falseAbstainRate)} | said "I don't remember" to an answerable question |`,
    `| abstention precision | ${pct(r.abstentionPrecision)} | of all abstentions, how many were right |`,
    `| abstention recall | ${pct(r.abstentionRecall)} | of out-of-scope questions, how many abstained |`,
  ];
  const fails = r.failures.length
    ? r.failures
        .map(
          (f) =>
            `- "${f.q}": expected ${f.expected ?? 'abstain'}, got ${f.got.join(', ') || 'abstained'}`,
        )
        .join('\n')
    : '- none';
  return `# Evals

Generated by \`npm run eval:write\` from \`src/eval/questions.ts\`; do not edit by hand. A test fails if
this file is out of date.

Embedder: \`${embedder}\`, abstention threshold: ${threshold}. Questions: ${r.inScope} answerable
+ ${r.outOfScope} unanswerable, all on the fictional demo persona (8 memories).

| metric | value | meaning |
| --- | --- | --- |
${rows.join('\n')}

## Misses

${fails}

## Caveats

- The corpus is eight memories, so recall@5 is close to trivially high; recall@1 and the wrong-answer
  rate are the informative numbers.
- The hashing embedder is lexical. The neural embedder has not been evaluated here and needs its own
  threshold.
- Questions were written by the same author as the persona; they are not an independent benchmark.
- The threshold was tuned on part of this set, so the reported numbers are optimistic.
`;
}
